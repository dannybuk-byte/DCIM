/**
 * Generate public/commit-hash.txt + src/generated/buildIdentity.ts (R-F13).
 * Read-back validates the public marker equals the resolved SHA.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveBuildIdentity } from './resolve-build-identity.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * @returns {{ commit: string, source: string }}
 */
export function generateBuildInfo() {
  const { commit, source } = resolveBuildIdentity();

  const publicPath = join(ROOT, 'public', 'commit-hash.txt');
  writeFileSync(publicPath, `${commit}\n`, 'utf8');

  const readBack = readFileSync(publicPath, 'utf8').trim();
  if (readBack !== commit) {
    throw new Error(
      `R-F13: commit-hash.txt read-back mismatch (wrote ${commit}, read ${readBack})`,
    );
  }

  const generatedDir = join(ROOT, 'src', 'generated');
  mkdirSync(generatedDir, { recursive: true });
  const generatedPath = join(generatedDir, 'buildIdentity.ts');
  const generated = [
    '// AUTO-GENERATED by scripts/generate-build-info.mjs — do not edit.',
    `export const BUILD_COMMIT = '${commit}' as const;`,
    `export const BUILD_IDENTITY_SOURCE = '${source}' as const;`,
    '',
  ].join('\n');
  writeFileSync(generatedPath, generated, 'utf8');

  const generatedRead = readFileSync(generatedPath, 'utf8');
  if (!generatedRead.includes(`'${commit}'`)) {
    throw new Error('R-F13: generated buildIdentity.ts missing resolved commit');
  }

  return { commit, source };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const { commit, source } = generateBuildInfo();
  console.log(`✅ Build identity: ${commit.slice(0, 7)} (${source})`);
}
